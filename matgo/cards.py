"""
1단계: 화투 카드 만들기

화투는 1월~12월, 월마다 4장씩 총 48장입니다.
카드 종류(kind)는 4가지입니다.
  - "광"   : 가장 높은 점수 카드 (5장)
  - "열끗" : 동물/그림 카드 (9장)
  - "띠"   : 리본(띠) 카드 (10장)
  - "피"   : 일반 카드 (24장, 쌍피 포함)
"""

import random


class Card:
    """화투 카드 한 장을 나타내는 클래스"""

    def __init__(self, month, kind, name, pi_value=0):
        self.month = month        # 몇 월 카드인지 (1~12)
        self.kind = kind          # "광", "열끗", "띠", "피"
        self.name = name          # 화면에 보여줄 이름 (예: "송학 광")
        self.pi_value = pi_value  # 피 점수 계산용 (피=1, 쌍피=2, 나머지=0)

    def __repr__(self):
        # print() 했을 때 보기 좋게 표시
        return f"[{self.month}월 {self.name}]"


# 월별 카드 구성표: (종류, 이름, 피 값)
CARD_TABLE = {
    1:  [("광", "송학 광", 0), ("띠", "홍단", 0), ("피", "피", 1), ("피", "피", 1)],
    2:  [("열끗", "매조 새", 0), ("띠", "홍단", 0), ("피", "피", 1), ("피", "피", 1)],
    3:  [("광", "벚꽃 광", 0), ("띠", "홍단", 0), ("피", "피", 1), ("피", "피", 1)],
    4:  [("열끗", "흑싸리 새", 0), ("띠", "초단", 0), ("피", "피", 1), ("피", "피", 1)],
    5:  [("열끗", "난초 다리", 0), ("띠", "초단", 0), ("피", "피", 1), ("피", "피", 1)],
    6:  [("열끗", "모란 나비", 0), ("띠", "청단", 0), ("피", "피", 1), ("피", "피", 1)],
    7:  [("열끗", "홍싸리 멧돼지", 0), ("띠", "초단", 0), ("피", "피", 1), ("피", "피", 1)],
    8:  [("광", "공산 광", 0), ("열끗", "공산 기러기", 0), ("피", "피", 1), ("피", "피", 1)],
    9:  [("열끗", "국진", 0), ("띠", "청단", 0), ("피", "피", 1), ("피", "피", 1)],
    10: [("열끗", "단풍 사슴", 0), ("띠", "청단", 0), ("피", "피", 1), ("피", "피", 1)],
    11: [("광", "오동 광", 0), ("피", "쌍피", 2), ("피", "피", 1), ("피", "피", 1)],
    12: [("광", "비 광", 0), ("열끗", "비 제비", 0), ("띠", "비띠", 0), ("피", "쌍피", 2)],
}


def make_deck():
    """48장 화투 덱을 만들어서 리스트로 돌려줍니다."""
    deck = []
    for month, cards in CARD_TABLE.items():
        for kind, name, pi_value in cards:
            deck.append(Card(month, kind, name, pi_value))
    return deck


def deal(deck):
    """
    맞고 규칙대로 카드를 나눕니다.
      - 플레이어 10장, 컴퓨터 10장
      - 바닥 8장
      - 나머지 20장은 더미(뒤집어 놓는 카드)
    """
    random.shuffle(deck)          # 카드 섞기
    player = deck[0:10]
    computer = deck[10:20]
    floor = deck[20:28]
    pile = deck[28:]              # 남은 20장
    return player, computer, floor, pile
